#!/usr/bin/env python3
"""Assemble the claim-controlled section drafts into one reviewable paper.

The section drafts remain the canonical editing sources.  This script performs
only deterministic extraction, author-comment removal, and heading-level
normalization; it never fills result slots or derives numbers from experiment
artifacts.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = REPOSITORY_ROOT / "docs" / "manuscript.md"
TITLE = "Certified Reachability-Constrained Decoding over Dynamic DRS States"


def _section(text: str, start: str, end: str, *, include_start: bool = False) -> str:
    """Return the unique source slice delimited by exact Markdown headings."""

    lines = text.splitlines()
    starts = [index for index, line in enumerate(lines) if line == start]
    ends = [index for index, line in enumerate(lines) if line == end]
    if len(starts) != 1 or len(ends) != 1 or starts[0] >= ends[0]:
        raise ValueError(
            f"expected one ordered section boundary {start!r} -> {end!r}"
        )
    first = starts[0] if include_start else starts[0] + 1
    return "\n".join(lines[first : ends[0]]).strip()


def _remove_author_comments(text: str) -> str:
    """Remove paragraph-role comments while leaving visible prose unchanged."""

    without_comments = re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)
    return re.sub(r"\n{3,}", "\n\n", without_comments).strip()


def _shift_headings(text: str, levels: int = 1) -> str:
    """Nest source subsection headings below their assembled paper section."""

    shifted: list[str] = []
    in_fence = False
    for line in text.splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        match = None if in_fence else re.match(r"^(#{1,5})(\s+.+)$", line)
        if match is None:
            shifted.append(line)
            continue
        level = len(match.group(1)) + levels
        if level > 6:
            raise ValueError(f"heading cannot be shifted below level 6: {line!r}")
        shifted.append("#" * level + match.group(2))
    return "\n".join(shifted)


def _read(relative: str, root: Path) -> str:
    return (root / relative).read_text(encoding="utf-8")


def assemble(root: Path = REPOSITORY_ROOT) -> str:
    """Build the unified manuscript from its six canonical section drafts."""

    abstract_source = _read("docs/manuscript-abstract.md", root)
    introduction_source = _read("docs/manuscript-scaffold.md", root)
    related_source = _read("docs/manuscript-related-work.md", root)
    method_source = _read("docs/manuscript-method.md", root)
    experiments_source = _read("docs/manuscript-experiments.md", root)
    conclusion_source = _read("docs/manuscript-conclusion.md", root)

    abstract = _remove_author_comments(
        _section(
            abstract_source,
            "## Version 2: Challenge → insight → contribution",
            "## Abstract reverse outline",
        )
    )
    introduction = _remove_author_comments(
        _section(
            introduction_source,
            "## Draft Introduction",
            "## Reverse outline",
        )
    )
    related = _shift_headings(
        _remove_author_comments(
            _section(
                related_source,
                "## 2.1 Grammar constraints and tokenizer alignment",
                "## Related-work reverse outline",
                include_start=True,
            )
        )
    )
    pipeline = _remove_author_comments(
        _section(method_source, "## Pipeline sketch", "## 3.1 Problem setting and guarantee target")
    )
    method = _shift_headings(
        _remove_author_comments(
            _section(
                method_source,
                "## 3.1 Problem setting and guarantee target",
                "## Method reverse outline",
                include_start=True,
            )
        )
    )
    experiments = _shift_headings(
        _remove_author_comments(
            _section(
                experiments_source,
                "## 4.1 Datasets and evaluation boundary",
                "## Experiment reverse outline",
                include_start=True,
            )
        )
    )
    conclusion = _remove_author_comments(
        _section(
            conclusion_source,
            "## Draft Conclusion",
            "## Conclusion reverse outline",
        )
    )

    parts = [
        "<!-- Generated by scripts/assemble_manuscript.py; edit the six "
        "docs/manuscript-*.md source drafts instead. -->",
        f"# {TITLE}",
        "## Abstract",
        abstract,
        "## 1 Introduction",
        introduction,
        "## 2 Related Work",
        related,
        "## 3 Method",
        "**Figure 1. Native-token reachability-constrained decoding and "
        "fail-closed release.**",
        pipeline,
        method,
        "## 4 Experiments",
        experiments,
        "## 5 Conclusion",
        conclusion,
    ]
    manuscript = "\n\n".join(parts).strip() + "\n"
    if manuscript.count("RESULT PENDING") < 34:
        raise ValueError("assembled manuscript lost one or more locked result slots")
    return manuscript


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the existing output differs; do not write",
    )
    args = parser.parse_args()
    rendered = assemble()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != rendered:
            parser.error(f"assembled manuscript is stale: {args.output}")
        print(f"manuscript assembly is current: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    print(f"assembled manuscript: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
